package com.example.nova

/**
 * Единственное место, где записано, у кого приложение спрашивает внешний адрес,
 * страну выхода и живость канала.
 *
 * Раньше рядом с Cloudflare в этих списках стояли ipify, icanhazip, ident.me,
 * ifconfig.me, а в пробе канала — ещё gstatic и google. Каждый такой адрес это
 * отдельная зависимость: чужая доступность, чужая политика и чужой формат ответа.
 * Хуже того, страну они не отдают вовсе, поэтому бейдж собирался из двух разных
 * источников — адрес от одного, страна от другого, — и они могли разойтись.
 *
 * Cloudflare в проекте и так основной: через него идут WARP и MASQUE. Поэтому
 * спрашиваем только его, зато с нескольких входов:
 *
 *  * литеральные адреса — вход без DNS, когда резолвер недоступен или подменён;
 *  * имена — единственный путь через HTTP-прокси, который к литералам не пускает;
 *  * отдельные входы для IPv4 и IPv6, иначе семью адреса выбирает не приложение.
 *
 * `/cdn-cgi/trace` отдаёт `ip=` и `loc=` одним ответом: адрес и страна всегда из
 * одного замера и разойтись не могут.
 */
object CloudflareTrace {

    const val PATH = "/cdn-cgi/trace"

    /** Конец строки HTTP — для проб, которые пишут запрос в сокет руками. */
    const val CRLF = "\r\n"

    /** Резолверы Cloudflare по литеральным адресам: DNS для них не нужен. */
    val IPV4_HOSTS = listOf("1.1.1.1", "1.0.0.1")
    val IPV6_HOSTS = listOf("2606:4700:4700::1111", "2606:4700:4700::1001")

    val IPV4_URLS = IPV4_HOSTS.map { "http://$it$PATH" }
    val IPV6_URLS = IPV6_HOSTS.map { "http://[$it]$PATH" }

    /**
     * Входы по имени. Нужны там, где литеральный адрес не проходит: HTTP-прокси
     * Opera ходит по именам, а часть сетей режет 1.1.1.1 адресно.
     */
    val HOSTNAME_URLS = listOf(
        "https://www.cloudflare.com$PATH",
        "https://cloudflare.com$PATH",
        "https://one.one.one.one$PATH",
    )

    /** Хосты для чтения trace через прокси-сокет: сначала литералы, потом имена. */
    val PROXY_TRACE_HOSTS = IPV4_HOSTS + listOf("www.cloudflare.com", "one.one.one.one")

    /**
     * Проба живости канала. Тело не нужно — важен сам код 200/204, поэтому первым
     * идёт самый дешёвый ответ Cloudflare, а следом trace по литеральным адресам.
     */
    val PROBE_URLS = listOf(
        "https://cp.cloudflare.com/generate_204",
        "http://1.1.1.1$PATH",
        "http://1.0.0.1$PATH",
        "https://www.cloudflare.com$PATH",
    )

    /** Хост для пробы через SOCKS/HTTP-прокси: литерал, чтобы не зависеть от DNS. */
    const val PROBE_HOST = "1.1.1.1"
}
