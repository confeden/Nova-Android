package com.example.nova

import java.util.Locale

/**
 * Обход неудачного узла Cloudflare — по узлу, а не по стране выхода.
 *
 * ## Почему именно так, а не «перебирать, пока страна выхода не станет зарубежной»
 *
 * Это две разные вещи, и путать их дорого.
 *
 * * **Узел** (`colo`, код вроде `DME`, `FRA`, `ARN`) — это край Cloudflare, куда
 *   привёл anycast от выбранной точки входа. Он **зависит от адреса**, который
 *   набирает клиент, и меняется от адреса к адресу даже внутри одной `/24`.
 * * **Страна выхода** — это геопривязка адреса, с которого Cloudflare выпускает
 *   трафик наружу. Cloudflare выбирает его так, чтобы страна совпадала со страной
 *   адреса клиента. Из российской сети выход будет российским, **какую точку входа
 *   ни возьми**: туннель может идти через Франкфурт и всё равно выходить как Россия.
 *
 * Регистрация на это не влияет вовсе: ответ `/v0aNNNN/reg` несёт только `id`,
 * `token`, публичный ключ узла и выданные адреса — ни страны, ни узла, ни точки
 * входа. Поэтому «перерегистрироваться, пока страна не станет зарубежной» — это
 * настройка, которая крутилась бы вечно и не срабатывала никогда, и её здесь нет
 * намеренно.
 *
 * ## Что здесь есть и почему этого достаточно
 *
 * Исходная жалоба — замедление YouTube, а это фильтрация DPI на трафике,
 * проходящем через московский узел, а не следствие страны выхода. Значит лечится
 * оно сменой **узла**: увидели `DME` — переходим к следующей точке входа.
 *
 * Объект чистый: ни контекста, ни ввода-вывода, ни времени. Решение о том, годится
 * ли узел, обязано быть проверяемым тестом, а не наблюдением на устройстве.
 */
object ExitColoPolicy {

    /**
     * Узлы, которых избегаем по умолчанию.
     *
     * `DME` — Москва. Список именно из кодов узлов, а не из стран: у Cloudflare в
     * России несколько краёв, и запрет по стране выключил бы заодно те, на которые
     * никто не жаловался.
     */
    val DEFAULT_AVOIDED = setOf("DME")

    /** Что делать с текущим узлом. */
    enum class Verdict {
        /** Узел годится или проверять нечего. */
        KEEP,

        /** Узел в списке нежелательных — берём следующую точку входа. */
        SWITCH,
    }

    /**
     * @param enabled включена ли настройка. Выключена — [Verdict.KEEP] всегда.
     * @param observedColo код узла из `/cdn-cgi/trace`. Пусто — узел неизвестен, и
     *        это **не** повод переключаться: неизвестность не улика.
     * @param avoided коды нежелательных узлов.
     * @param switchesSoFar сколько раз уже переключались в этой сессии.
     * @param switchBudget потолок переключений.
     */
    fun evaluate(
        enabled: Boolean,
        observedColo: String?,
        avoided: Set<String> = DEFAULT_AVOIDED,
        switchesSoFar: Int = 0,
        switchBudget: Int = DEFAULT_SWITCH_BUDGET,
    ): Verdict {
        if (!enabled) return Verdict.KEEP
        val colo = observedColo?.trim()?.uppercase(Locale.US).orEmpty()
        // Пустой код — узел не измерен. Переключаться на этом основании значило бы
        // ходить по кругу на сети, где `/cdn-cgi/trace` вообще не отвечает.
        if (colo.isEmpty()) return Verdict.KEEP
        if (colo !in avoided.map { it.trim().uppercase(Locale.US) }.toSet()) return Verdict.KEEP
        // Потолок обязателен. Если нежелательный узел — единственный достижимый,
        // без него настройка превращается в бесконечное переподключение, то есть в
        // «интернет не работает», а не в «работает медленнее».
        if (switchesSoFar >= switchBudget) return Verdict.KEEP
        return Verdict.SWITCH
    }

    /**
     * Сколько раз готовы сменить точку входа за сессию.
     *
     * Пять — это компромисс: каждый переход стоит полного переподключения с
     * обрывом соединений, а список точек входа anycast'овый, и попадание на другой
     * узел не гарантировано ни на первой попытке, ни на пятой.
     */
    const val DEFAULT_SWITCH_BUDGET = 5

    /** Строка для журнала: что увидели и что решили. */
    fun describe(colo: String?, verdict: Verdict, switchesSoFar: Int, budget: Int): String {
        val shown = colo?.trim()?.uppercase(Locale.US).orEmpty().ifEmpty { "неизвестен" }
        return when (verdict) {
            Verdict.KEEP -> "Узел Cloudflare: $shown — оставляем."
            Verdict.SWITCH ->
                "Узел Cloudflare: $shown в списке нежелательных — берём следующую точку входа " +
                    "(${switchesSoFar + 1} из $budget)."
        }
    }
}
