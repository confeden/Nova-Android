package com.example.nova

/**
 * Порядок перебора профилей и наказание неудачных.
 *
 * Правило одно и общее для всех протоколов и обоих источников — встроенных и
 * импортированных: **не подключились к текущему профилю — молча берём следующий,
 * а текущий уводим вниз списка**. Пауз и остановок между попытками нет; для
 * пользователя переключение выглядит как продолжение одного подключения, а не как
 * новая попытка, которую надо запускать руками.
 *
 * Логика вынесена из хранилища отдельным объектом, потому что она чистая: список
 * на входе, список на выходе. Внутри [ClientData] ту же перестановку пришлось бы
 * проверять на устройстве, а здесь она проверяется обычными unit-тестами.
 */
object ProfileRotation {

    /**
     * С какого места начинать перебор: с активной записи, иначе с начала списка.
     *
     * Перебор идёт по самому списку, а не по его перестановке, и это принципиально:
     * номер, который видит пользователь, — это место профиля в списке. Стоило начать
     * перебор с перестановки, и номера считались бы от неё: подключённый профиль
     * показывался «7/151», хотя в списке стоял шестым.
     */
    fun <T> startIndex(items: List<T>, active: T?): Int {
        if (items.isEmpty() || active == null) return 0
        return items.indexOf(active).takeIf { it >= 0 } ?: 0
    }

    /**
     * Поднимает удачный профиль в начало списка.
     *
     * Без этого рабочий узел так и оставался бы в середине: над ним лежали бы записи,
     * которых перебор в этот раз не касался, и «следующий профиль» уводил бы не вниз
     * от рабочего, а куда-то в непроверенную часть списка.
     */
    fun <T> promote(items: List<T>, good: T): List<T> {
        val index = items.indexOf(good)
        if (index <= 0) return items
        val result = ArrayList<T>(items.size)
        result.add(good)
        items.forEachIndexed { i, item -> if (i != index) result.add(item) }
        return result
    }

    /**
     * Уводит неудачный профиль в конец списка, сохраняя порядок остальных.
     *
     * Возвращает исходный список, если двигать нечего: профиля нет, или он уже
     * последний. Вызывающая сторона по этому признаку решает, надо ли писать в
     * хранилище.
     */
    fun <T> demote(items: List<T>, bad: T): List<T> {
        val index = items.indexOf(bad)
        if (index < 0 || index == items.lastIndex) return items
        val result = ArrayList<T>(items.size)
        result.addAll(items)
        result.removeAt(index)
        result.add(bad)
        return result
    }

    /**
     * Складывает свежий список с уже известным, сохраняя выстроенный порядок.
     *
     * Свежий ответ отвечает на вопрос «что вообще есть», а накопленный порядок — на
     * вопрос «с чего начинать». Прямая замена теряла второе: наверху известного
     * списка стоит запись, поднятая туда после удачного удержания, а свежий ответ
     * приходит в своём порядке и клал её в середину.
     *
     * Известные записи, которых в свежем ответе нет, отбрасываются: их больше не
     * предлагают, и держать их в очереди — значит платить за них попытками.
     */
    fun <T> mergeKeepingOrder(known: List<T>, fresh: List<T>): List<T> {
        if (fresh.isEmpty()) return known
        val freshSet = fresh.toSet()
        val kept = known.filter { it in freshSet }
        val keptSet = kept.toSet()
        return kept + fresh.filterNot { it in keptSet }
    }

    /** Что осталось от списка после удаления и какая запись стала активной. */
    data class Removal<T>(val items: List<T>, val active: T?)

    /**
     * Убирает профиль из списка и решает, какой станет активным.
     *
     * Возвращает `null`, если удалять было нечего: по этому признаку вызывающая
     * сторона решает, писать ли в хранилище и что показать пользователю. Молчаливое
     * «удалили ноль записей» — это ровно тот случай, когда список остаётся прежним,
     * а пользователь уверен, что удаление сработало.
     *
     * Активной могла быть как раз удалённая запись: тогда активной становится первая
     * оставшаяся, иначе перебор начинался бы с профиля, которого в списке уже нет.
     */
    fun <T> remove(items: List<T>, active: T?, match: (T) -> Boolean): Removal<T>? {
        val remaining = items.filterNot(match)
        if (remaining.size == items.size) return null
        val nextActive = active?.takeIf { it in remaining } ?: remaining.firstOrNull()
        return Removal(remaining, nextActive)
    }

    /** Следующий профиль за текущим, с закольцовыванием. */
    fun <T> next(items: List<T>, current: T?): T? {
        if (items.isEmpty()) return null
        val index = items.indexOf(current)
        if (index < 0) return items.first()
        return items[(index + 1) % items.size]
    }
}
