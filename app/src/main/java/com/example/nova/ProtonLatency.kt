package com.example.nova

import java.net.InetSocketAddress
import java.net.Socket

/**
 * Замер задержки до узла Proton по TCP — им ранжируется весь список.
 *
 * Зачем он нужен. Настоящее рукопожатие WireGuard
 * ([ProtonCrypto.probeHandshakeRttMs]) сильнее: оно и меряет задержку, и
 * доказывает, что узел знает наш ключ. Но рукопожатием нельзя мерить **список** —
 * доведённое до конца рукопожатие отбирает ключ у живого туннеля, а узел, которому
 * они надоели, замолкает на 25+ минут (`kb/proton-generator.md`, Nova PC
 * `kb/profiles.md#wg-probe`). Поэтому рукопожатие уходит одно, в голову очереди, а
 * порядок задаёт этот замер. Без него ранжирование падало на `Load` из API: список
 * сортировался по загруженности сервера, а не по задержке до него, и первым в
 * очереди оказывался не ближайший узел, а наименее занятый — на другом континенте.
 *
 * Что меряет этот замер. Обычное TCP-соединение к тому же входному адресу. Узлы
 * Proton держат на нём OpenVPN TCP, и порт 443 отвечает: замер с рабочей машины по
 * шести встроенным узлам дал 61 мс до NO, 74 мс до NL, 150-154 мс до CA и 215 мс
 * до US — то есть числа, упорядоченные ровно так, как предсказывает география, а
 * один узел из шести не ответил вовсе. Это не рукопожатие и ничего не доказывает
 * про ключ, но путь до узла — тот же самый, и для **порядка** этого достаточно.
 *
 * Чего он не значит. Живость по UDP он не предсказывает совсем: на ПК на TCP 443
 * ответили 50 узлов из 50, из них 36 молчали на рукопожатие на любом порту. «Узел
 * ответил по TCP» — это «сервер жив и вот столько до него лететь», не более.
 *
 * Почему не ICMP. `InetAddress.isReachable` без root на Android сводится к попытке
 * TCP на порт 7, которого у Proton нет, а сырой ICMP-сокет требует своей возни с
 * `Os.socket` и молча зависит от `ping_group_range`. TCP-соединение проверяемо и
 * работает везде, где вообще работает сеть.
 *
 * Честность выдачи: результат этого замера **помечается** ([ProtonProfile.pingSource]),
 * и «лучший 61 мс» в журнале не выдаётся за подтверждённое рукопожатие.
 */
object ProtonLatency {

    /**
     * Порт для замера.
     *
     * Один, а не список: замер идёт параллельно с рукопожатием и обязан уложиться в
     * его срок, иначе он добавит время к прогону вместо того, чтобы прятаться в
     * нём. Перебор трёх портов по три секунды на мёртвом узле стоил бы девяти —
     * дороже самого рукопожатия.
     */
    const val TCP_PORT = 443

    /** Метка источника замера — она же уезжает в `proton_profiles.json`. */
    const val SOURCE_HANDSHAKE = "handshake"
    const val SOURCE_TCP = "tcp"
    const val SOURCE_NONE = ""

    /**
     * Время установления TCP-соединения с [host].
     *
     * @param protect защита сокета от собственного туннеля и привязка к нижележащей
     *        сети — то же, что у рукопожатия, и по той же причине: замер обязан
     *        описывать прямой путь до узла, а не канал уже поднятого туннеля.
     *        Вызывается **до** `connect`: и `protect()`, и `Network.bindSocket()`
     *        меняют маршрут пакета целиком и на уже соединённом сокете бесполезны.
     * @return RTT в миллисекундах или -1, если соединение не установилось.
     */
    fun probeTcpRttMs(
        host: String,
        port: Int = TCP_PORT,
        timeoutMs: Int,
        protect: ((Socket) -> Unit)? = null,
    ): Int {
        var socket: Socket? = null
        return try {
            val address = InetSocketAddress(host, port)
            if (address.isUnresolved) return -1
            socket = Socket()
            protect?.invoke(socket)
            val startedAt = System.nanoTime()
            socket.connect(address, timeoutMs)
            ((System.nanoTime() - startedAt) / 1_000_000L).toInt().coerceAtLeast(1)
        } catch (_: Exception) {
            -1
        } finally {
            runCatching { socket?.close() }
        }
    }
}
