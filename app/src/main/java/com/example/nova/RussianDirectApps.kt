    /**
     * Возвращает `true`, если [packageName] является банковским приложением из закрытого списка.
     *
     * Проверка источника установки (например, RuStore / Google Play) остаётся **за вызывающей
     * стороной** — этот метод только сверяет имя пакета.
     */
    fun isBanking(packageName: String): Boolean = packageName in BANKING

    /**
     * Возвращает `true`, если [packageName] присутствует в закрытом списке прямых (non-VPN)
     * приложений — будь то банк ([BANKING]) или любой другой российский сервис ([OTHER]).
     *
     * Список **намеренно закрытый**: открытая эвристика (например, «все приложения из RuStore»)
     * затащила бы произвольные пакеты в исключения туннеля и создала бы дыры в маршрутизации.
     * Новые пакеты добавляются только вручную после проверки.
     */
    fun contains(packageName: String): Boolean =
        packageName in BANKING || packageName in OTHER

    /**
     * Возвращает объединение всех пакетов из [BANKING] и [OTHER].
     */
    fun all(): Set<String> = BANKING + OTHER
